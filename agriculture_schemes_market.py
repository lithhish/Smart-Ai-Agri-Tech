def get_schemes(category: Optional[str] = None, search: Optional[str] = None) -> List[Dict[str, Any]]:
    """Filter government schemes by category or keyword search."""
    items = GOVERNMENT_SCHEMES
    if category and category != "all":
        items = [s for s in items if category.lower() in s["category"].lower() or category.lower() in s["id"]]
    if search and search.strip():
        q = search.strip().lower()
        items = [
            s for s in items
            if q in s["title"].lower() or q in s["category"].lower() or q in s["financial_support"].lower() or q in s["key_benefits"].lower()
        ]
    return items


